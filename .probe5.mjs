import { chromium } from '@playwright/test';
setTimeout(() => { console.log('GLOBAL TIMEOUT'); process.exit(2); }, 60000);
const url = process.argv[2];
const b = await chromium.launch();
const page = await (await b.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
page.on('pageerror', e => console.log('pageerror', e.message));
page.on('console', m => m.type() === 'error' && console.log('console', m.text()));
await page.goto(url);
const snap = async (label) => console.log(label, await page.evaluate(() => ({ ready: document.documentElement.className, screens: document.querySelector('.screens')?.children.length, stageHidden: document.querySelector('.stage')?.hidden, hit: document.elementFromPoint(200,200)?.className, newRect: JSON.stringify(document.querySelector('.gallery-new')?.getBoundingClientRect()) })));
await snap('t0');
await page.waitForSelector('[data-testid=gallery-new], .gallery-new', { timeout: 20000 });
await snap('gallery');
const r = await page.locator('.gallery-new').boundingBox();
await page.mouse.click(r.x + r.width/2, r.y + r.height/2);
await page.waitForTimeout(500);
console.log('overlay', await page.locator('.theme-overlay').count());
await page.locator('[aria-label=Meadow]').click();
await page.waitForFunction(() => window.__tibuTest && window.__tibuTest.worldCount() > 0, null, { timeout: 15000 });
const c0 = await page.evaluate(() => window.__tibuTest.worldCount());
const p = await page.evaluate(() => window.__tibuTest.cellToScreen(11, 1, 12));
await page.mouse.click(p.x, p.y);
await page.waitForTimeout(300);
console.log('count', c0, await page.evaluate(() => window.__tibuTest.worldCount()), await page.evaluate(() => window.__tibuTest.getBlock(11,2,12)));
process.exit(0);
